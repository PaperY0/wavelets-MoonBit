"""Generate wavelet_data.mbt from the PyWavelets reference implementation.

The filter coefficients are emitted with 17 significant digits so the MoonBit
Doubles are bit-identical to pywt's.  Run from the project root:

    python tools/gen_wavelets.py

Requires the local reference install (tools/ref/pylibs, see
tools/ref/requirements.txt).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(HERE, "ref", "pylibs"))
import pywt

SYMMETRY = {
    "asymmetric": "Asymmetric",
    "near symmetric": "NearSymmetric",
    "symmetric": "Symmetric",
    "anti-symmetric": "AntiSymmetric",
    "unknown": "Asymmetric",
}


def d(x):
    """17-significant-digit literal (round-trips to the same float64)."""
    return repr(float(x))


def arr(xs):
    return "[" + ", ".join(d(x) for x in xs) + "]"


def main():
    lines = []
    lines.append("// GENERATED by tools/gen_wavelets.py from PyWavelets "
                 f"{pywt.__version__} — do not edit by hand.")
    lines.append("// Filter coefficients are bit-identical to pywt (17 significant digits).")
    lines.append("")
    lines.append("///|")
    lines.append("/// 离散小波的滤波器组与元数据（移植自 PyWavelets 内置小波表）。")
    lines.append("struct DiscreteSpec {")
    lines.append("  name : String")
    lines.append("  family_name : String")
    lines.append("  short_name : String")
    lines.append("  orthogonal : Bool")
    lines.append("  biorthogonal : Bool")
    lines.append("  symmetry : Symmetry")
    lines.append("  vm_psi : Int")
    lines.append("  vm_phi : Int")
    lines.append("  dec_lo : Array[Double]")
    lines.append("  dec_hi : Array[Double]")
    lines.append("  rec_lo : Array[Double]")
    lines.append("  rec_hi : Array[Double]")
    lines.append("}")
    lines.append("")
    lines.append("///|")
    lines.append("let discrete_specs : Array[DiscreteSpec] = [")
    names = pywt.wavelist(kind="discrete")
    for name in names:
        w = pywt.Wavelet(name)
        vm_psi = w.vanishing_moments_psi
        vm_phi = w.vanishing_moments_phi
        lines.append("  {")
        lines.append(f"    name: {json.dumps(name)},")
        lines.append(f"    family_name: {json.dumps(w.family_name)},")
        lines.append(f"    short_name: {json.dumps(w.short_family_name)},")
        lines.append(f"    orthogonal: {str(bool(w.orthogonal)).lower()},")
        lines.append(f"    biorthogonal: {str(bool(w.biorthogonal)).lower()},")
        lines.append(f"    symmetry: {SYMMETRY[w.symmetry]},")
        lines.append(f"    vm_psi: {vm_psi if vm_psi is not None else 0},")
        lines.append(f"    vm_phi: {vm_phi if vm_phi is not None else 0},")
        lines.append(f"    dec_lo: {arr(w.dec_lo)},")
        lines.append(f"    dec_hi: {arr(w.dec_hi)},")
        lines.append(f"    rec_lo: {arr(w.rec_lo)},")
        lines.append(f"    rec_hi: {arr(w.rec_hi)},")
        lines.append("  },")
    lines.append("]")
    lines.append("")
    lines.append("///|")
    lines.append("/// 连续小波（实值）的支撑区间与元数据。复值小波族（cgau/shan/fbsp/cmor）")
    lines.append("/// 不在 v0.1 范围内，见 docs/known-deviations.md。")
    lines.append("struct ContinuousSpec {")
    lines.append("  name : String")
    lines.append("  family_name : String")
    lines.append("  short_name : String")
    lines.append("  symmetry : Symmetry")
    lines.append("  lower_bound : Double")
    lines.append("  upper_bound : Double")
    lines.append("}")
    lines.append("")
    lines.append("///|")
    lines.append("let continuous_specs : Array[ContinuousSpec] = [")
    real_continuous = [n for n in pywt.wavelist(kind="continuous")
                       if not pywt.ContinuousWavelet(n).complex_cwt]
    for name in real_continuous:
        w = pywt.ContinuousWavelet(name)
        lines.append("  {")
        lines.append(f"    name: {json.dumps(name)},")
        lines.append(f"    family_name: {json.dumps(w.family_name)},")
        lines.append(f"    short_name: {json.dumps(w.short_family_name)},")
        lines.append(f"    symmetry: {SYMMETRY[w.symmetry]},")
        lines.append(f"    lower_bound: {d(w.lower_bound)},")
        lines.append(f"    upper_bound: {d(w.upper_bound)},")
        lines.append("  },")
    lines.append("]")
    lines.append("")

    out = os.path.join(ROOT, "wavelet_data.mbt")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {out}: {len(names)} discrete + {len(real_continuous)} continuous wavelets")


if __name__ == "__main__":
    main()